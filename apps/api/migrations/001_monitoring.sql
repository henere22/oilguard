CREATE TABLE system_settings (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  data_mode text NOT NULL CHECK (data_mode IN ('simulation', 'operational'))
);

CREATE TABLE tanks (
  id text PRIMARY KEY,
  name text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('clean', 'used')),
  capacity_liters double precision,
  attention_threshold double precision NOT NULL CHECK (attention_threshold BETWEEN 0 AND 100),
  critical_threshold double precision NOT NULL CHECK (critical_threshold BETWEEN 0 AND 100),
  level_percent double precision CHECK (level_percent BETWEEN 0 AND 100),
  updated_at timestamptz
);

CREATE TABLE readings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tank_id text NOT NULL REFERENCES tanks(id),
  level_percent double precision NOT NULL CHECK (level_percent BETWEEN 0 AND 100),
  measured_at timestamptz NOT NULL,
  received_at timestamptz NOT NULL,
  device_id text
);
CREATE INDEX readings_tank_measured ON readings(tank_id, measured_at DESC, id DESC);
CREATE INDEX readings_measured ON readings(measured_at DESC, id DESC);

CREATE TABLE alerts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tank_id text NOT NULL REFERENCES tanks(id),
  severity text NOT NULL CHECK (severity IN ('attention', 'critical')),
  title text NOT NULL,
  message text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL,
  resolved_at timestamptz
);
CREATE INDEX alerts_created ON alerts(created_at DESC);
CREATE UNIQUE INDEX alerts_active_tank ON alerts(tank_id) WHERE is_active;

CREATE TABLE legacy_imports (
  fingerprint text PRIMARY KEY,
  counts jsonb NOT NULL,
  imported_at timestamptz NOT NULL DEFAULT now()
);

